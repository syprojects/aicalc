const DICTS: Record<Lang, Dict> = { tr, en };
const KEY = 'aicalc-lang';

function initialLang(): Lang {
  const q = new URLSearchParams(window.location.search).get('lang');
  if (q === 'tr' || q === 'en') return q;
  try {
    const s = localStorage.getItem(KEY);
    if (s === 'tr' || s === 'en') return s;
  } catch {
    /* depolama kapalı olabilir */
  }
  return navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

const I18nContext = createContext<{ lang: Lang; t: Dict; toggle: () => void }>({ lang: 'tr', t: tr, toggle: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);
  setFormatLang(lang);
  useEffect(() => {
    const t = DICTS[lang];
    document.documentElement.lang = lang;
    document.title = t.meta.title;
    document.querySelector('meta[name="description"]')?.setAttribute('content', t.meta.description);
    try {
      localStorage.setItem(KEY, lang);
    } catch {
      /* depolama kapalı olabilir */
    }
  }, [lang]);
  const toggle = useCallback(() => setLang((l) => (l === 'tr' ? 'en' : 'tr')), []);
  return <I18nContext.Provider value={{ lang, t: DICTS[lang], toggle }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
